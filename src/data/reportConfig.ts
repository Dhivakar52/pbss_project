/** Helper to format any field key into a user-friendly human readable label */
export function formatHeaderLabel(key: string): string {
  if (customLabelMap[key]) return customLabelMap[key]

  return key
    .replace(/_/g, ' ')
    .replace(/([a-z])([A-Z])/g, '$1 $2')
    .toLowerCase()
    .split(' ')
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join(' ')
}

/** Helper to build Column definitions from raw field array */
function buildColumns(keys: string[]): ReportColumnConfig[] {
  return keys.map((key) => ({
    key,
    label: formatHeaderLabel(key),
    sortable: true,
  }))
}

